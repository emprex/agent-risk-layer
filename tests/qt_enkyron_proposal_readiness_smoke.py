"""ENK-04 exact-company proposal readiness: native read-only Qt IPC tests."""
import gc
import os
import unittest
from unittest.mock import patch

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6.QtCore import QEvent
from PySide6.QtWidgets import QApplication, QDialog
from desktop.enkyron import DesktopBridge, EnkyronWindow

COMPANY = "11111111-2222-4333-8444-555555555555"
OPPORTUNITY = "22222222-3333-4444-8555-666666666666"
OTHER = "33333333-4444-4555-8666-777777777777"
REVIEW = "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee"


class ProposalReadinessSmoke(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.app = QApplication.instance() or QApplication([])

    def setup_window(self):
        calls = []
        original = DesktopBridge.call

        def fake_call(_self, command, arg="", payload=None, callback=None):
            calls.append((command, arg, payload, callback))

        DesktopBridge.call = fake_call
        try:
            window = EnkyronWindow()
            dialog = QDialog(window)
            dialog.show()
            self.app.processEvents()
            window.crm_dossier_dialog = dialog
            window.crm_dossier_company_id = COMPANY
            # Ignore normal Home/ticket/profile reads triggered by startup.
            # Each test asserts only IPC generated by the preparation action.
            calls.clear()
            return window, dialog, calls, original
        except Exception:
            DesktopBridge.call = original
            raise

    def close(self, window, dialog, original):
        try:
            dialog.reject()
            window.close()
            window.deleteLater()
            QApplication.sendPostedEvents(None, QEvent.Type.DeferredDelete)
            self.app.processEvents()
            gc.collect()
        finally:
            DesktopBridge.call = original

    def opportunity(self, company=COMPANY):
        return {
            "opportunity_id": OPPORTUNITY, "company_id": company,
            "source_ticket_id": None, "stage": "qualified"
        }

    def test_valid_exact_scope_readback_is_advisory_only(self):
        window, dialog, calls, original = self.setup_window()
        try:
            with patch("desktop.enkyron.QMessageBox.information") as info:
                window.review_dossier_proposal_preparation(
                    self.opportunity(), COMPANY
                )
                self.assertEqual(len(calls), 1)
                command, arg, payload, callback = calls[0]
                self.assertEqual(command, "crm-company-proposal-readiness")
                self.assertEqual(arg, COMPANY + ":" + OPPORTUNITY)
                self.assertIsNone(payload)
                callback({
                    "available": True, "company_id": COMPANY,
                    "company_name": "Synthetic Engineering Ltd",
                    "opportunity_id": OPPORTUNITY,
                    "opportunity": {"stage": "qualified"},
                    "qualification": {"id": REVIEW, "fit_status": "potential_fit"},
                    "existing_draft_count": 0,
                    "eligible_for_internal_draft_review": True,
                    "blockers": [], "external_issue_authorised": False
                }, None)
                self.assertEqual(info.call_count, 1)
                message = info.call_args.args[2]
                self.assertIn("READ-ONLY CHECK", message)
                self.assertIn("no", message.lower())
                self.assertFalse(any(c[0] in {
                    "crm-proposal-create", "crm-proposal-update",
                    "create-ticket", "mail-send-draft", "assessment-link",
                } for c in calls))
        finally:
            self.close(window, dialog, original)

    def test_wrong_company_and_bad_link_are_denied(self):
        window, dialog, calls, original = self.setup_window()
        try:
            with patch("desktop.enkyron.QMessageBox.warning") as warning, \
                 patch("desktop.enkyron.QMessageBox.information") as info:
                window.review_dossier_proposal_preparation(
                    self.opportunity(company=OTHER), COMPANY
                )
                self.assertFalse(calls)
                self.assertTrue(warning.called)
                window.review_dossier_proposal_preparation(
                    self.opportunity(), COMPANY
                )
                calls[-1][3]({
                    "available": True, "company_id": OTHER,
                    "opportunity_id": OPPORTUNITY, "blockers": [],
                    "eligible_for_internal_draft_review": True
                }, None)
                self.assertFalse(info.called)
                self.assertGreaterEqual(warning.call_count, 2)
        finally:
            self.close(window, dialog, original)

    def test_late_response_after_company_change_is_ignored(self):
        window, dialog, calls, original = self.setup_window()
        try:
            with patch("desktop.enkyron.QMessageBox.information") as info, \
                 patch("desktop.enkyron.QMessageBox.warning") as warning:
                window.review_dossier_proposal_preparation(
                    self.opportunity(), COMPANY
                )
                window.crm_dossier_company_id = OTHER
                calls[-1][3]({
                    "available": True, "company_id": COMPANY,
                    "opportunity_id": OPPORTUNITY,
                    "eligible_for_internal_draft_review": True,
                    "blockers": []
                }, None)
                self.assertFalse(info.called)
                self.assertFalse(warning.called)
                self.assertEqual(len(calls), 1)
        finally:
            self.close(window, dialog, original)


if __name__ == "__main__":
    unittest.main()
